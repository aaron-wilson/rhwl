import { color, splash, tintAliases, type ThemedColor } from "./color.ts";
import {
  blur,
  breakpoint,
  container,
  duration,
  easing,
  font,
  layer,
  radius,
  shadow,
  space,
  text,
  weight,
  device,
} from "./scale.ts";

const HEADER = "/* Generated by scripts/generate-tokens.ts from src/tokens. Do not edit. */";
type Theme = "light" | "dark";

const entries = <V>(record: Readonly<Record<string, V>>): [string, V][] => Object.entries(record);

function block(selector: string, lines: string[], indent = ""): string {
  const body = lines.map((line) => `${indent}  ${line}`).join("\n");
  return `${indent}${selector} {\n${body}\n${indent}}`;
}

function themed(theme: Theme): string[] {
  const colors = (prefix: string, record: Record<string, ThemedColor>) =>
    entries(record).map(([name, value]) => `--rh-color-${prefix}${name}: ${value[theme]};`);
  return [
    `color-scheme: ${theme};`,
    ...colors("", color),
    ...colors("splash-", splash),
    ...entries(shadow).map(([name, value]) => `--rh-shadow-${name}: ${value[theme]};`),
  ];
}

function tint(kind: "gain" | "loss"): string[] {
  return entries(tintAliases).map(
    ([alias, target]) => `--rh-color-${alias}: var(--rh-color-${target[kind]});`,
  );
}

function statics(): string[] {
  return [
    ...entries(space).map(([k, v]) => `--rh-space-${k}: ${v}px;`),
    ...entries(radius).map(([k, v]) => `--rh-radius-${k}: ${v}px;`),
    ...entries(duration).map(([k, v]) => `--rh-duration-${k}: ${v}ms;`),
    ...entries(easing).map(([k, v]) => `--rh-ease-${k}: ${v};`),
    ...entries(blur).map(([k, v]) => `--rh-blur-${k}: ${v}px;`),
    ...entries(layer).map(([k, v]) => `--rh-layer-${k}: ${v};`),
    ...entries(device).map(([k, v]) => `--rh-device-${k}: ${v}px;`),
    `--rh-font-sans: ${font.sans};`,
    `--rh-font-mono: ${font.mono};`,
  ];
}

/**
 * Custom properties for both themes. Theme and tint blocks also match nested
 * [data-theme] elements, because a var() alias resolves where it is declared.
 */
export function generateTokensCss(): string {
  return [
    HEADER,
    block(":root", statics()),
    block(':root,\n[data-theme="light"]', themed("light")),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', themed("dark"), "  ")}\n}`,
    block('[data-theme="dark"]', themed("dark")),
    block(
      ':root,\n[data-theme],\n[data-tint="gain"],\n[data-tint="gain"] [data-theme]',
      tint("gain"),
    ),
    block('[data-tint="loss"],\n[data-tint="loss"] [data-theme]', tint("loss")),
    "",
  ].join("\n\n");
}

/** Tailwind v4 theme mapping. Only these utilities exist; the default palette is never loaded. */
export function generateThemeCss(): string {
  const colorNames = [
    ...Object.keys(color),
    ...Object.keys(tintAliases),
    ...Object.keys(splash).map((name) => `splash-${name}`),
  ];
  const theme = [
    ...colorNames.map((name) => `--color-${name}: var(--rh-color-${name});`),
    "--color-transparent: transparent;",
    "--color-current: currentColor;",
    ...entries(space).map(([k]) => `--spacing-${k}: var(--rh-space-${k});`),
    ...entries(radius).map(([k]) => `--radius-${k}: var(--rh-radius-${k});`),
    ...entries(text).flatMap(([k, v]) => [
      `--text-${k}: ${v.size}px;`,
      `--text-${k}--line-height: ${v.line}px;`,
      `--text-${k}--letter-spacing: ${v.tracking}em;`,
    ]),
    ...entries(weight).map(([k, v]) => `--font-weight-${k}: ${v};`),
    "--font-sans: var(--rh-font-sans);",
    "--font-mono: var(--rh-font-mono);",
    ...entries(shadow).map(([k]) => `--shadow-${k}: var(--rh-shadow-${k});`),
    ...entries(easing).map(([k]) => `--ease-${k}: var(--rh-ease-${k});`),
    ...entries(blur).map(([k]) => `--blur-${k}: var(--rh-blur-${k});`),
    ...entries(breakpoint).map(([k, v]) => `--breakpoint-${k}: ${v}px;`),
    ...entries(container).map(([k, v]) => `--container-${k}: ${v}px;`),
    "--default-font-family: var(--rh-font-sans);",
    "--default-mono-font-family: var(--rh-font-mono);",
    "--default-transition-duration: var(--rh-duration-base);",
    "--default-transition-timing-function: var(--rh-ease-standard);",
  ];
  const utilities = [
    ...entries(duration).map(
      ([k]) => `@utility duration-${k} {\n  transition-duration: var(--rh-duration-${k});\n}`,
    ),
    ...entries(layer).map(([k]) => `@utility layer-${k} {\n  z-index: var(--rh-layer-${k});\n}`),
  ];
  return [HEADER, block("@theme inline", theme), ...utilities, ""].join("\n\n");
}
